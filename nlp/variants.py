# 简→繁单字偏好：一个简化字对应多个传统字时的默认选择（未被词组命中时）
TRAD_PREFERENCE = {
    "发": "發", "钟": "鐘", "复": "復", "台": "臺", "里": "裡", "后": "後",
    "干": "幹", "准": "準", "才": "才", "只": "只", "卷": "卷", "舍": "舍",
    "占": "占", "曲": "曲", "克": "克", "系": "係", "须": "須", "脏": "髒",
    "恶": "惡", "汇": "匯", "历": "歷", "坛": "壇", "团": "團", "当": "當",
    "尽": "盡", "于": "於", "云": "雲", "蜡": "蠟", "腊": "臘", "签": "簽",
    "弥": "彌", "面": "面", "谷": "谷", "姜": "姜", "松": "松", "咸": "咸",
    "表": "表", "板": "板",
}

_PLACEHOLDER_BASE = 0xE000


def _parse_pairs(raw: str) -> dict[str, str]:
    """解析 ``繁简 繁简 …`` 形式的成对字符串。"""
    table: dict[str, str] = {}
    for token in raw.split():
        token = token.strip()
        if len(token) >= 2 and token[0] != token[1]:
            table[token[0]] = token[1]
    return table


def _parse_phrases(raw: str) -> dict[str, str]:
    """解析等长繁简词组（按长度切半）。"""
    phrases: dict[str, str] = {}
    for token in raw.split():
        token = token.strip()
        if len(token) >= 4 and len(token) % 2 == 0:
            half = len(token) // 2
            left, right = token[:half], token[half:]
            if left != right:
                phrases[left] = right
    return phrases


def _parse_keep(raw: str) -> set[str]:
    return {t for t in raw.split() if t and not t.endswith("?")}


def _load_override(base: dict[str, str]) -> None:
    """合并外部字表（若存在），每行 ``繁体 简体``，空格或逗号分隔。"""
    candidates = []
    env = os.environ.get("NLP_T2S_DATA")
    if env:
        candidates.append(env)
    here = os.path.dirname(os.path.abspath(__file__))
    candidates.append(os.path.join(here, "t2s_override.txt"))
    for path in candidates:
        if not path or not os.path.exists(path):
            continue
        try:
            with open(path, "r", encoding="utf-8") as fh:
                for line in fh:
                    line = line.strip()
                    if not line or line.startswith("#"):
                        continue
                    parts = line.replace(",", " ").replace("\t", " ").split()
                    if len(parts) >= 2 and len(parts[0]) == 1 and len(parts[1]) == 1:
                        base[parts[0]] = parts[1]
        except OSError:
            continue


class ChineseConverter:
    """繁→简 / 简→繁转换器（线程安全，只读数据）。"""

    def __init__(self):
        t2s = _parse_pairs(_T2S_CHARS)
        _load_override(t2s)
        self.t2s = t2s
        self.s2t = self._build_s2t(t2s)
        self.t2s_phrases = _parse_phrases(_T2S_PHRASES_RAW)
        self.s2t_phrases = _parse_phrases(_S2T_PHRASES_RAW)
        self.t2s_keep = _parse_keep(_T2S_KEEP_RAW)
        # 身份词组也作为"保留"处理
        self.s2t_keep = {l for l, r in self.s2t_phrases.items() if l == r}
        self._t2s_phrase_re = self._phrase_re(self.t2s_phrases, self.t2s_keep)
        self._s2t_phrase_re = self._phrase_re(self.s2t_phrases, set())
        self.trad_only = set(t2s) - set(t2s.values())
        self.simp_only = set(t2s.values()) - set(t2s)

    @staticmethod
    def _build_s2t(t2s: dict[str, str]) -> dict[str, str]:
        s2t: dict[str, str] = {}
        for trad, simp in t2s.items():
            if simp in TRAD_PREFERENCE:
                s2t[simp] = TRAD_PREFERENCE[simp]
            elif simp not in s2t:
                s2t[simp] = trad
        return s2t

    @staticmethod
    def _phrase_re(phrases: dict[str, str], keep: set[str]) -> Optional[re.Pattern]:
        keys = sorted(set(phrases) | keep, key=len, reverse=True)
        if not keys:
            return None
        return re.compile("|".join(re.escape(k) for k in keys))

    # -- 对外接口 ---------------------------------------------------------
    def to_simplified(self, text: str) -> str:
        return self._convert(
            text, self._t2s_phrase_re, self.t2s_phrases, self.t2s_keep, self.t2s)

    def to_traditional(self, text: str) -> str:
        return self._convert(
            text, self._s2t_phrase_re, self.s2t_phrases, self.s2t_keep, self.s2t)

    # -- 核心 -------------------------------------------------------------
    def _convert(self, text: str, phrase_re: Optional[re.Pattern],
                 phrases: dict[str, str], keep: set[str],
                 char_map: dict[str, str]) -> str:
        if not text:
            return text
        masks: list[str] = []

        def _take_mask(s: str) -> str:
            masks.append(s)
            return chr(_PLACEHOLDER_BASE + len(masks) - 1)

        # 1) 词组级替换 / 保留（占位符保护）
        if phrase_re is not None:
            def _repl(match: re.Match) -> str:
                hit = match.group()
                if hit in keep:
                    return _take_mask(hit)
                return _take_mask(phrases.get(hit, hit))
            text = phrase_re.sub(_repl, text)

        # 2) 逐字转换（跳过占位符）
        out: list[str] = []
        for ch in text:
            code = ord(ch)
            if _PLACEHOLDER_BASE <= code < _PLACEHOLDER_BASE + len(masks):
                out.append(ch)
            else:
                out.append(char_map.get(ch, ch))
        text = "".join(out)

        # 3) 还原占位符
        for i, saved in enumerate(masks):
            text = text.replace(chr(_PLACEHOLDER_BASE + i), saved)
        return text


_lock = threading.Lock()
_instance: Optional[ChineseConverter] = None


def get_converter() -> ChineseConverter:
    """进程级单例。"""
    global _instance
    with _lock:
        if _instance is None:
            _instance = ChineseConverter()
        return _instance
