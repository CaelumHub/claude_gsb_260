# 归并类繁体：其简体形本身就是传统中文里在用的字（或承担别的字义），
# 简→繁 时不可自动反转。
_MERGE_TRAD = {
    "後", "裡", "裏", "麵", "臺", "檯", "颱", "鬆", "鬥", "捨", "鹹",
    "準", "佔", "雲", "鬱", "闆", "餘", "颳", "傑", "穀", "週", "徵",
    "捲", "築", "匯", "於", "隻", "煙", "夥", "澱", "製", "豐", "係",
    "兇", "註", "誇", "劃", "種", "彆", "闢", "幹",
}


def _build_tables() -> tuple[dict[str, str], dict[str, str]]:
    t2s: dict[str, str] = {}
    for line in _T2S_PAIRS.splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        for token in line.split():
            if len(token) != 2:
                raise ValueError(f"字表项必须为「繁简」二字组: {token!r}")
            trad, simp = token[0], token[1]
            if trad == simp:
                raise ValueError(f"字表项无变化: {token!r}")
            if trad in t2s and t2s[trad] != simp:
                raise ValueError(f"繁体字 {trad} 存在冲突映射: {t2s[trad]} / {simp}")
            t2s[trad] = simp

    # 反向：统计每个简体字的繁体来源数
    source_count: dict[str, int] = {}
    for simp in t2s.values():
        source_count[simp] = source_count.get(simp, 0) + 1

    s2t: dict[str, str] = {}
    for trad, simp in t2s.items():
        if source_count[simp] > 1:        # 歧义（發/髮→发、須/鬚→须）
            continue
        if trad in _MERGE_TRAD:           # 归并字（面/麵 类）
            continue
        s2t[simp] = trad
    return t2s, s2t


T2S, S2T = _build_tables()

