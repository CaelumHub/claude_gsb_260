def to_simplified(char: str) -> str:
    """单字繁→简，无映射时原样返回。"""
    return T2S.get(char, char)


def to_traditional(char: str) -> str:
    """单字简→繁（保守策略，见模块说明）。"""
    return S2T.get(char, char)
